"""Pin the Crontab Entries artifact (scripts/artifacts/linuxCron.py, linuxCrontabEntries).

USER_KNOWN is var/spool/cron/crontabs/parallels of ubuntu2604_arm64_crontab byte for byte: the file crontab 3.0pl1-200ubuntu1
wrote when it installed a known file. For every line below that cron accepts, the expected setting or command is
what cron's own load_env() and load_entry(), built from that package's sources, read from it; cron rejects the
system line '* * * * *  root', whose user name runs to the end of the line.
"""
