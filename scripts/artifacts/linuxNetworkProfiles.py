from datetime import datetime, timedelta, timezone

import yaml

from scripts.ilapfuncs import artifact_processor, logfunc

_EPOCH = datetime(1970, 1, 1, tzinfo=timezone.utc)
_ESCAPES = {'s': ' ', 'n': '\n', 't': '\t', 'r': '\r', '\\': '\\'}
# netplan's device types, the mappings under "network"
DEVICE_TYPES = ('bonds', 'bridges', 'dummy-devices', 'ethernets', 'modems', 'tunnels', 'virtual-ethernets', 'vlans',
                'vrfs', 'wifis', 'nm-devices')
_DEVICE_SHOWN = ('renderer', 'networkmanager', 'access-points', 'match', 'set-name', 'dhcp4', 'dhcp6', 'addresses')
_POINT_SHOWN = ('networkmanager', 'hidden', 'auth', 'password')
# the keys read inside a mapping the row shows part of
_INSIDE_SHOWN = {'match': ('macaddress',), 'networkmanager': ('name', 'uuid'), 'auth': ('key-management', 'password')}
_GROUPS_SHOWN = ('connection', 'wifi', '802-11-wireless', 'wifi-security', '802-11-wireless-security', 'ipv4', 'ipv6')


def utc(text):
    """The UTC time of a count of seconds since 1970 written in decimal digits, or '' for anything else and for 0,
    which NetworkManager uses for a profile that was never activated."""
    text = text.strip()
    if not text.isascii() or not text.isdigit() or int(text) == 0:
        return ''
    try:
        return _EPOCH + timedelta(seconds=int(text))
    except OverflowError:
        return ''


def key_file(data):
    """The groups of a key file: group name to a dict of key to value, a later value of a key replacing an earlier
    one, and the number of non-empty lines that are neither a comment, a group header nor a key with a value. A
    value has its leading white space removed and the escapes for space, new line, tab, carriage return and
    backslash replaced."""
    groups, current, skipped = {}, None, 0
    for raw in data.decode('utf-8', 'backslashreplace').split('\n'):
        line = raw.rstrip('\r')
        if not line.strip() or line.startswith('#'):
            continue
        if line.startswith('[') and line.rstrip().endswith(']'):
            current = groups.setdefault(line.rstrip()[1:-1], {})
            continue
        key, separator, value = line.partition('=')
        if not separator or current is None or not key.strip():
            skipped += 1
            continue
        current[key.strip()] = _unescape(value.lstrip())
    return groups, skipped


def _unescape(value):
    out, index = [], 0
    while index < len(value):
        char = value[index]
        if char == '\\' and index + 1 < len(value) and value[index + 1] in _ESCAPES:
            out.append(_ESCAPES[value[index + 1]])
            index += 2
        else:
            out.append(char)
            index += 1
    return ''.join(out)


def profile_row(groups):
    """(timestamp, name, uuid, type, interface, ssid, hidden, key management, pre-shared key, autoconnect, ipv4
    method, ipv6 method, other groups) for a profile's key file groups, or None when it has no connection group."""
    connection = groups.get('connection')
    if connection is None:
        return None
    wifi = groups.get('wifi', groups.get('802-11-wireless', {}))
    security = groups.get('wifi-security', groups.get('802-11-wireless-security', {}))
    return (utc(connection.get('timestamp', '')), connection.get('id', ''), connection.get('uuid', ''),
            connection.get('type', ''), connection.get('interface-name', ''), wifi.get('ssid', ''),
            wifi.get('hidden', ''), security.get('key-mgmt', ''), security.get('psk', ''),
            connection.get('autoconnect', ''), groups.get('ipv4', {}).get('method', ''),
            groups.get('ipv6', {}).get('method', ''),
            ', '.join(name for name in groups if name not in _GROUPS_SHOWN))


def _read(path):
    with open(path, 'rb') as handle:
        return handle.read()


def _files(context, *suffixes):
    """The found files, sorted, that are not folders and whose evidence path ends with or holds one of the texts."""
    picked = []
    for path in sorted(str(p) for p in context.get_files_found() if not os.path.isdir(p)):
        relative = context.get_relative_path(path).replace('\\', '/')
        if any(text in '/' + relative for text in suffixes):
            picked.append(path)
    return picked


def _log(label, counts):
    if counts:
        logfunc(label + ': ' + ', '.join(f'{count} {kind}' for kind, count in sorted(counts.items())))


