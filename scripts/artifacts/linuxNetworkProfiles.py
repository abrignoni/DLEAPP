def _text(value):
    """A YAML value as text: a scalar as written, a sequence joined with ' | ', a mapping as its keys."""
    if isinstance(value, (list, tuple)):
        return ' | '.join(_text(item) for item in value)
    if isinstance(value, dict):
        return ' | '.join(str(key) for key in value)
    return '' if value is None else str(value)


def _mapping(value):
    return value if isinstance(value, dict) else {}


def _unshown(mapping, shown, prefix=''):
    """The names of the keys of a device or access point that the row reads nothing from: a key not in shown, and
    for a mapping the row reads part of, each of its other keys after the mapping's name."""
    names = []
    for key, value in mapping.items():
        if key not in shown:
            names.append(prefix + str(key))
        elif key in _INSIDE_SHOWN:
            names.extend(f'{prefix}{key} {inner}' for inner in _mapping(value) if inner not in _INSIDE_SHOWN[key])
    return names


def load_netplan(data):
    """A netplan file's document with every scalar kept as the text written, which the base loader does: the safe
    loader would turn an unquoted password of digits or a network name such as No into another value."""
    return yaml.load(data, Loader=yaml.BaseLoader)


def netplan_rows(document):
    """(device type, device id, renderer, NetworkManager name, NetworkManager uuid, ssid, hidden, key management,
    password, MAC match, set name, dhcp4, dhcp6, addresses, other keys) for each device of a netplan document and,
    for a device with access points, for each of them. A renderer key directly under a device type is that type's
    renderer, not a device."""
    network = _mapping(_mapping(document).get('network'))
    rows = []
    for kind in DEVICE_TYPES:
        section = _mapping(network.get(kind))
        type_renderer = section.get('renderer') if not isinstance(section.get('renderer'), dict) else None
        for device_id, device in section.items():
            if device_id == 'renderer' and not isinstance(device, dict):
                continue
            device = _mapping(device)
            backend = _mapping(device.get('networkmanager'))
            renderer = device.get('renderer', type_renderer if type_renderer is not None else network.get('renderer'))
            common = (_text(renderer),)
            tail = (_text(_mapping(device.get('match')).get('macaddress')), _text(device.get('set-name')),
                    _text(device.get('dhcp4')), _text(device.get('dhcp6')), _text(device.get('addresses')))
            other = _unshown(device, _DEVICE_SHOWN)
            points = _mapping(device.get('access-points'))
            if not points:
                rows.append((kind, _text(device_id)) + common
                            + (_text(backend.get('name')), _text(backend.get('uuid')), '', '', '', '')
                            + tail + (', '.join(other),))
            for ssid, point in points.items():
                point = _mapping(point)
                own = _mapping(point.get('networkmanager'))
                auth = _mapping(point.get('auth'))
                password = auth['password'] if 'password' in auth else point.get('password')
                rows.append((kind, _text(device_id)) + common
                            + (_text(own.get('name', backend.get('name'))), _text(own.get('uuid', backend.get('uuid'))),
                               _text(ssid), _text(point.get('hidden')), _text(auth.get('key-management')),
                               _text(password))
                            + tail + (', '.join(other + _unshown(point, _POINT_SHOWN, 'access point ')),))
    return rows


